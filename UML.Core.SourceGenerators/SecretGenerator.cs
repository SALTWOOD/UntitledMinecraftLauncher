using System;
using System.Collections;
using System.Collections.Generic;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace UML.Core.SourceGenerators;

[Generator(LanguageNames.CSharp)]
public sealed class SecretGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var secrets = context.CompilationProvider.Select(static (_, _) => Collect());

        context.RegisterSourceOutput(secrets, static (spc, pairs) => Emit(spc, pairs));
    }

    private static IReadOnlyList<KeyValuePair<string, string>> Collect()
    {
        var result = new List<KeyValuePair<string, string>>();

#pragma warning disable RS1035
        if (Environment.GetEnvironmentVariable("UML_WRITE_SECRET") != "1")
            return result;

        try
        {
            foreach (DictionaryEntry entry in Environment.GetEnvironmentVariables())
            {
                if (entry.Key is not string key || entry.Value is null) continue;
                if (!key.StartsWith("UML_", StringComparison.Ordinal)) continue;
                if (key == "UML_WRITE_SECRET") continue;

                var value = entry.Value.ToString();
                if (string.IsNullOrWhiteSpace(value)) continue;

                result.Add(new KeyValuePair<string, string>(key.Substring(4), value));
            }
        }
        catch (Exception)
        {
            result.Clear();
        }
#pragma warning restore RS1035

        return result;
    }

    private static void Emit(SourceProductionContext context, IReadOnlyList<KeyValuePair<string, string>> pairs)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine("namespace UML.Core.App;");
        builder.AppendLine();
        builder.AppendLine("public static partial class Secrets");
        builder.AppendLine("{");
        builder.AppendLine("    private static global::System.Collections.Generic.Dictionary<string, string?> CreateEmbeddedSecrets() =>");
        builder.AppendLine("        new()");
        builder.AppendLine("        {");

        foreach (var pair in pairs)
            builder.AppendLine($"            [\"{pair.Key}\"] = {ToVerbatimString(pair.Value)},");

        builder.AppendLine("        };");
        builder.AppendLine("}");

        context.AddSource("Secrets.g.cs", SourceText.From(builder.ToString(), Encoding.UTF8));
    }

    private static string ToVerbatimString(string value) =>
        "@\"" + value.Replace("\"", "\"\"") + "\"";
}
